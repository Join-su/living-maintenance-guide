"""Shared DB administration (shared DB design v1.0 5·6.4 and appendix A·B, week-1 application): the local PostgreSQL that holds
`trace` (run records) and `task10` (Pack business data).

  python db/dbadmin.py env       write db/.env with a random password per account; an existing file keeps its passwords and only
                                 gets the lines it misses (no value is printed)
  python db/dbadmin.py init      superuser: accounts, the databases llmopsagent and llmopsagent_test (owned by db_owner), vector
                                 extension, public revoked, search_path, public USAGE for the two task10 accounts (vector type)
  python db/dbadmin.py migrate   db_owner: apply db/migrations/NNNN_*.sql in order to both databases, record number·name·sha256 in
                                 llmops.schema_version
  python db/dbadmin.py status    applied change files

Passwords live only in db/.env (ignored by git). Every message names accounts and files, never values."""
import argparse
import hashlib
import os
import re
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV_FILE = HERE / ".env"
MIGRATIONS = HERE / "migrations"
DB_NAME = "llmopsagent"
TEST_DB_NAME = "llmopsagent_test"   # the Pack side's loader tests (TASK10_PG_TEST_DSN, instruction 015b)
HOST = "127.0.0.1"
DEFAULT_PORT = "55432"
HOST_VAR = "LLMOPSAGENT_PG_HOST"   # EV-VPS-01 CHG-V08: the DSN host — a line of the env file (the VPS one says postgres), kept only when present
CONTAINER_MARKS = ("/.dockerenv", "/run/.containerenv")
LOOPBACK = ("127.0.0.1", "localhost", "::1")
ROLES = {  # account → (password variable, DSN variable, search_path); DSN names are the ones the Pack side uses (instruction 015b)
    "db_owner": ("DB_OWNER_PASSWORD", "LLMOPSAGENT_OWNER_DSN", None),
    "task10_loader": ("TASK10_LOADER_PASSWORD", "TASK10_LOADER_DSN", ("task10", "public")),
    "runtime_reader": ("RUNTIME_READER_PASSWORD", "LLMOPSAGENT_RUNTIME_DSN", ("task10", "public")),
    "trace_writer": ("TRACE_WRITER_PASSWORD", "LLMOPSAGENT_TRACE_DSN", ("trace",)),
    "llmops_app": ("LLMOPS_APP_PASSWORD", "LLMOPS_APP_DSN", ("trace",)),   # EV-025 CHG-127: the LLMOps server reads trace (SELECT only, 0004)
    "index_loader": ("INDEX_LOADER_PASSWORD", "LLMOPSAGENT_INDEX_LOADER_DSN", ("c1a15", "public")),   # D-298 Q-3 · D-363 (6): packrt.index load (INSERT only, 0011)
}
# the vector type and vector_dims live in public: these accounts may use (never create in) it (instruction 015b 2)
PUBLIC_USAGE = ("task10_loader", "runtime_reader", "index_loader")
OBSOLETE = ("LLMOPSAGENT_TASK10_LOADER_DSN",)
FILE_RE = re.compile(r"^(\d{4})_([a-z0-9_]+)\.sql$")


class AdminError(RuntimeError):
    pass


def read_env(path=ENV_FILE):
    out = {}
    if not Path(path).is_file():
        return out
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def dsn(user, password, port, dbname=DB_NAME, host=HOST):
    return f"postgresql://{user}:{password}@{host}:{port}/{dbname}"


def write_env(path=ENV_FILE, port=DEFAULT_PORT):
    """Create the env file, or bring an existing one up to date: passwords already there are kept, missing lines are added and
    obsolete names removed. Returns "created", "updated" or "current". Values are never printed."""
    path = Path(path)
    old = read_env(path) if path.exists() else {}
    port = old.get("LLMOPSAGENT_PG_PORT", port)
    host = old.get(HOST_VAR) or ""   # only a line already in the file (CHG-V08, review VS-3 L-6): no line → no new line, the DSNs keep 127.0.0.1
    pw = {k: old.get(k) or secrets.token_urlsafe(24) for k in ("POSTGRES_PASSWORD", *(p for p, _, _ in ROLES.values()))}
    want = {"LLMOPSAGENT_PG_PORT": port, **({HOST_VAR: host} if host else {}), **pw,
            "LLMOPSAGENT_SUPERUSER_DSN": dsn("postgres", pw["POSTGRES_PASSWORD"], port, "postgres", host or HOST)}
    for role, (pvar, dvar, _) in ROLES.items():
        want[dvar] = dsn(role, pw[pvar], port, host=host or HOST)
    want["TASK10_PG_TEST_DSN"] = dsn("task10_loader", pw["TASK10_LOADER_PASSWORD"], port, TEST_DB_NAME, host or HOST)
    if old and all(old.get(k) == v for k, v in want.items()) and not any(k in old for k in OBSOLETE):
        os.chmod(path, 0o600)
        return "current"
    extra = {k: v for k, v in old.items() if k not in want and k not in OBSOLETE}   # lines a person added stay
    lines = ["# llmopsagent local PostgreSQL (db/compose.yaml). Generated by db/dbadmin.py env. Never commit, never print.",
             *(f"{k}={v}" for k, v in {**want, **extra}.items())]
    tmp = path.with_name(path.name + ".new")
    tmp.unlink(missing_ok=True)
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)
    return "updated" if old else "created"


def _connect(conninfo, **kw):
    import psycopg
    try:
        return psycopg.connect(conninfo, connect_timeout=5, **kw)
    except psycopg.OperationalError as e:
        # libpq messages do not carry passwords, but keep only the first line and drop anything after "password"
        first = str(e).splitlines()[0] if str(e) else type(e).__name__
        raise AdminError(f"DB에 연결할 수 없습니다: {first.split('password')[0].strip()}") from None


def _with_db(conninfo, dbname):
    return re.sub(r"/[^/?]*(\?|$)", f"/{dbname}\\1", conninfo, count=1)


# Tests set this False (EV-029 UF-PG1-3): a test's fresh database must not re-set the passwords of the cluster's existing shared
# accounts; missing accounts are still created with their db/.env password.
SET_EXISTING_PASSWORDS = True


def init(env, dbname=DB_NAME, set_existing_passwords=None):
    """Superuser part of appendix B: accounts (password kept in step with db/.env), the database owned by db_owner, the vector
    extension, public revoked, CONNECT for the accounts and a fixed search_path per account. Safe to run again."""
    if set_existing_passwords is None:
        set_existing_passwords = SET_EXISTING_PASSWORDS
    from psycopg import sql
    su = env.get("LLMOPSAGENT_SUPERUSER_DSN")
    if not su:
        raise AdminError("db/.env에 LLMOPSAGENT_SUPERUSER_DSN이 없습니다(dbadmin env)")
    with _connect(su, autocommit=True) as c:
        for role, (pvar, _, _) in ROLES.items():
            if not env.get(pvar):
                raise AdminError(f"db/.env에 {pvar}가 없습니다")
            exists = c.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (role,)).fetchone()
            if exists and not set_existing_passwords:
                continue
            verb = "ALTER" if exists else "CREATE"
            c.execute(sql.SQL(verb + " ROLE {} LOGIN PASSWORD {}").format(sql.Identifier(role), sql.Literal(env[pvar])))
        if not c.execute("SELECT 1 FROM pg_database WHERE datname = %s", (dbname,)).fetchone():
            c.execute(sql.SQL("CREATE DATABASE {} OWNER db_owner").format(sql.Identifier(dbname)))
    with _connect(_with_db(su, dbname), autocommit=True) as c:
        c.execute("CREATE EXTENSION IF NOT EXISTS vector")
        c.execute("REVOKE ALL ON SCHEMA public FROM PUBLIC")
        c.execute(sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(sql.Identifier(dbname)))
        c.execute(sql.SQL("GRANT CONNECT ON DATABASE {} TO {}").format(sql.Identifier(dbname), sql.SQL(", ").join(sql.Identifier(r) for r in ROLES)))
        c.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(sql.SQL(", ").join(sql.Identifier(r) for r in PUBLIC_USAGE)))
        for role, (_, _, path) in ROLES.items():
            if path:
                c.execute(sql.SQL("ALTER ROLE {} IN DATABASE {} SET search_path = {}").format(sql.Identifier(role), sql.Identifier(dbname),
                                                                                             sql.SQL(", ").join(sql.Identifier(p) for p in path)))


def migration_files(folder=MIGRATIONS):
    out = []
    for p in sorted(Path(folder).glob("*.sql")):
        m = FILE_RE.match(p.name)
        if not m:
            raise AdminError(f"변경 파일 이름이 NNNN_name.sql 모양이 아닙니다: {p.name}")
        out.append((int(m.group(1)), m.group(2), p))
    nums = [n for n, _, _ in out]
    if nums != list(range(1, len(nums) + 1)):
        raise AdminError(f"변경 파일 번호가 1부터 빈칸 없이 이어지지 않습니다: {nums}")
    return out


def applied(conn):
    if not conn.execute("SELECT to_regclass('llmops.schema_version')").fetchone()[0]:
        return {}
    return {v: (n, s) for v, n, s in conn.execute("SELECT version, name, sha256 FROM llmops.schema_version ORDER BY version")}


def migrate(env, dbname=DB_NAME, folder=MIGRATIONS):
    """Apply the change files that are not applied yet, each in one transaction, as db_owner. A recorded file whose content
    changed since it was applied is refused (change files are never edited; a new number is added instead)."""
    owner = env.get("LLMOPSAGENT_OWNER_DSN")
    if not owner:
        raise AdminError("db/.env에 LLMOPSAGENT_OWNER_DSN이 없습니다(dbadmin env)")
    done = []
    with _connect(_with_db(owner, dbname)) as c:
        have = applied(c)
        files = migration_files(folder)
        names = {num: name for num, name, _ in files}
        gone = [f"{v:04d}_{n}" for v, (n, _) in sorted(have.items()) if names.get(v) != n]
        if gone:   # an applied change file is missing or renamed: the folder no longer describes this database
            raise AdminError(f"적용된 변경 파일이 폴더에 없거나 이름이 바뀌었습니다: {', '.join(gone)}")
        for num, name, path in files:
            text = path.read_text(encoding="utf-8")
            digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
            if num in have:
                if have[num][1] != digest:
                    raise AdminError(f"이미 적용한 변경 파일 {path.name}의 내용이 바뀌었습니다(새 번호로 더해야 합니다)")
                continue
            with c.transaction():
                c.execute(text)
                c.execute("INSERT INTO llmops.schema_version (version, name, sha256) VALUES (%s, %s, %s)", (num, name, digest))
            done.append(path.name)
    return done


def status(env, dbname=DB_NAME):
    if not env.get("LLMOPSAGENT_OWNER_DSN"):
        raise AdminError("db/.env에 LLMOPSAGENT_OWNER_DSN이 없습니다(dbadmin env)")
    with _connect(_with_db(env["LLMOPSAGENT_OWNER_DSN"], dbname)) as c:
        return sorted((v, n) for v, (n, _) in applied(c).items())


def _platform():
    return sys.platform


def where_refusal(command, env_file):
    """EV-VPS-01 CHG-V08: why this run must not go on (Linux only), or None. On a Linux host the default address 127.0.0.1:55432 can be
    another product's database on the same server, so dbadmin runs only inside the compose container, and there never against the
    container's own loopback. No connection is made here and no value is printed."""
    if not _platform().startswith("linux"):
        return None
    if not any(os.path.exists(m) for m in CONTAINER_MARKS):
        return (f"리눅스 호스트에서는 dbadmin을 돌리지 않습니다 — 같은 서버의 다른 DB(호스트 {DEFAULT_PORT})에 붙을 수 있습니다. "
                f"docker compose run --rm llmops python db/dbadmin.py {command}으로 컨테이너 안에서 돌리세요")
    from urllib.parse import urlsplit
    env = read_env(env_file)
    if command == "env":
        hosts = [env.get(HOST_VAR) or HOST]
    else:
        hosts = [urlsplit(env[k]).hostname for k in ("LLMOPSAGENT_SUPERUSER_DSN", "LLMOPSAGENT_OWNER_DSN") if env.get(k)]
    if any(h in LOOPBACK for h in hosts):
        return f"컨테이너 안에서 DSN 호스트가 이 컨테이너 자신(loopback)입니다 — {HOST_VAR}=postgres로 env 파일을 만드세요"
    return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("command", choices=["env", "init", "migrate", "status"])
    ap.add_argument("--env-file", default=str(ENV_FILE))
    a = ap.parse_args(argv)
    why = where_refusal(a.command, a.env_file)
    if why:
        print(f"dbadmin {a.command}: {why}", file=sys.stderr)
        return 2
    try:
        if a.command == "env":
            state = write_env(a.env_file)
            print(f"{a.env_file}: " + {"created": "만들었습니다(계정 비밀번호 7개, DSN 8개, 값은 출력하지 않음)",
                                       "updated": "빠진 줄을 더했습니다(기존 비밀번호 그대로, 값은 출력하지 않음)",
                                       "current": "최신입니다(그대로 둠)"}[state])
            return 0
        env = read_env(a.env_file)
        if not env:
            raise AdminError(f"{a.env_file}가 없습니다 — 먼저 `python db/dbadmin.py env`")
        if a.command == "init":
            for name in (DB_NAME, TEST_DB_NAME):
                init(env, dbname=name)
            print(f"init: 계정 {', '.join(ROLES)}, DB {DB_NAME}·{TEST_DB_NAME}(소유 db_owner), vector 확장, public 회수, search_path 고정")
        elif a.command == "migrate":
            for name in (DB_NAME, TEST_DB_NAME):
                done = migrate(env, dbname=name)
                print(f"migrate {name}: " + (", ".join(done) if done else "적용할 변경 파일 없음(최신)"))
        else:
            for v, n in status(env):
                print(f"{v:04d} {n}")
        return 0
    except AdminError as e:
        print(f"dbadmin {a.command}: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
