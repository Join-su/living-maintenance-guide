-- EV-035 CHG-188 (approved E3, answer 045-01 · D-181): the improvement wheel's rows (a row = one tried change, not a version — D-121)
-- and the spend of its paid steps, with the SAME tables and columns as llmops/store.py SCHEMA (SQLite). auto_spend is append only by
-- GRANT alone (no trigger, so a wheel delete removes it by CASCADE). Not in the store's start check: without these tables the wheel
-- stops before ③. Run by db_owner through dbadmin migrate; the shared databases only after the user's separate approval.
CREATE TABLE llmops.auto_candidate (
  candidate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wheel_id bigint NOT NULL REFERENCES llmops.auto_wheel(wheel_id) ON DELETE CASCADE,
  iteration integer NOT NULL,
  hypothesis_ids text NOT NULL,              -- JSON list of auto_hypothesis ids (same node only, Q-4 A)
  node text NOT NULL, lines text NOT NULL,   -- change lines in the edit-line shape (editing.add, source auto)
  revision text, check_result text NOT NULL DEFAULT '{}',
  cheap_test text,                           -- JSON: predicted cases · changed k / n
  table_result text,                         -- JSON: per execution — per case route · checks · state · tokens · ms · output sha; set counts
  executions integer NOT NULL DEFAULT 0, rank integer,
  outcome text,                              -- discarded · table_out · winner · next_row
  recommendation text,                       -- JSON from the grading agent (adopt / reject · reasons) — not a verdict
  release_id text REFERENCES llmops.releases(id) ON DELETE SET NULL,   -- the version it became
  created_at double precision NOT NULL, updated_at double precision NOT NULL);
CREATE TABLE llmops.auto_spend (
  spend_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wheel_id bigint NOT NULL REFERENCES llmops.auto_wheel(wheel_id) ON DELETE CASCADE,
  step text NOT NULL, calls integer NOT NULL, tokens_in bigint NOT NULL, tokens_out bigint NOT NULL,
  usd double precision NOT NULL, model text NOT NULL, created_at double precision NOT NULL);
GRANT SELECT, INSERT, UPDATE, DELETE ON llmops.auto_candidate TO llmops_app;
GRANT SELECT, INSERT ON llmops.auto_spend TO llmops_app;   -- append only by grant alone, no trigger (0007 way: CASCADE still removes rows)
GRANT USAGE, SELECT ON SEQUENCE llmops.auto_candidate_candidate_id_seq, llmops.auto_spend_spend_id_seq TO llmops_app;
