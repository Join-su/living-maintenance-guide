-- D-486 덧 9 (089-a · packrt-1 077): every use of a sealed test set outside an improvement wheel — a release a person picked as the final
-- candidate (POST …/sealed-check with a reason) — with the SAME table and columns as llmops/store.py SCHEMA (SQLite). A wheel's own use
-- stays its wheel log line; the two together are a set's count (at most its limit, a version once). Append only by grant alone (no
-- trigger) and no foreign key: deleting a release or a Project never lowers a set's count. Counts only, never a case or an answer.
-- Not in the store's start check: without it only the call outside a wheel is refused. Run by db_owner through dbadmin migrate;
-- the shared databases only after the user's separate approval. Back: db/migrations-down/0013_sealed_use.sql.
CREATE TABLE llmops.sealed_use (
  use_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  set_sha12 text NOT NULL,                   -- the set's recorded sha256, first 12
  project_id text NOT NULL, release_id text NOT NULL,
  revision text NOT NULL DEFAULT '',        -- D-486 덧 14: the candidate's revision — a version once is once per revision
  base_release_id text NOT NULL,            -- ids as text: the row outlives them
  result text NOT NULL CHECK (result IN ('통과', '떨어짐', '상한 멈춤', '설정 실패')),   -- 덧 13: '설정 실패' is kept, never counted
  called_by text NOT NULL CHECK (length(trim(called_by)) > 0),
  reason text NOT NULL CHECK (length(trim(reason)) > 0),   -- why the person picked it
  counts text NOT NULL DEFAULT '{}',         -- JSON: n · broken · fixed · upper · groups ('{}' when the call's cap cut it)
  usd double precision NOT NULL DEFAULT 0,   -- the two Runs' spend (real mode) = measured + estimated, counted with the wheels' spend
  usd_measured double precision NOT NULL DEFAULT 0,    -- D-486 덧 12: the visits' own tokens × prices
  usd_estimated double precision NOT NULL DEFAULT 0,   -- the careful unit where no usage came back (a retriever's embedding, an unpriced model)
  line text NOT NULL,                        -- the record's words
  created_at double precision NOT NULL);
GRANT SELECT, INSERT ON llmops.sealed_use TO llmops_app;   -- append only by grant alone (0008 way)
GRANT USAGE, SELECT ON SEQUENCE llmops.sealed_use_use_id_seq TO llmops_app;
