-- EV-030 CHG-150 (approved E3, answer 026-01): the auto-cycle records in the shared PostgreSQL `llmops` schema with the SAME
-- tables and columns as llmops/store.py SCHEMA (SQLite), so both Store backends keep one meaning. JSON stays text, times stay epoch
-- seconds (double precision). Stored diagnosis holds results only — no payload text, node input or output (Q-11). Append only
-- (review_label · auto_wheel_log · auto_hypothesis) is by GRANT alone — no trigger — so a Project · release delete removes them by
-- CASCADE (AC-21; avoids the K-6 / UF-OPS3-1 problem). These tables are NOT in the store's start check: a server on a database
-- without this migration starts and keeps the auto cycle off. Run by db_owner through dbadmin migrate; the shared databases only
-- after the user's separate approval (bundled with D-145's K-6 change).
CREATE TABLE llmops.ops_diagnosis (
  diagnosis_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE,
  release_id text NOT NULL REFERENCES llmops.releases(id) ON DELETE CASCADE,
  run_id text NOT NULL,                       -- trace run id (logDB; not a foreign key — trace is the deploy side's)
  deployment_id text NOT NULL, pack_revision text NOT NULL,
  batch text NOT NULL,                        -- one batch = the new operational Runs found in one pass (띠 'k / n')
  status text NOT NULL CHECK (status IN ('waiting', 'running', 'done', 'error')),
  rule_result text, ratio_result text, judge_result text,   -- JSON results only: check names · ✓/✗ · ratio numbers · rubric item names · reason ≤200 chars (raw-value overlaps masked)
  judge_kind text CHECK (judge_kind IN ('fake', 'harness', 'real', 'skipped')),   -- fake = shown only, not a signal (Q-9)
  rubric_version text NOT NULL DEFAULT 'none', judge_model text,   -- NOT NULL so the unique key below holds for judge-skipped rows too
  signal text CHECK (signal IN ('fail', 'pass', 'normal', 'none')),
  suspect_node text, error_kind text,         -- no_dsn · unreachable · denied · broken (kind only)
  created_at double precision NOT NULL, finished_at double precision,
  UNIQUE (project_id, run_id, rubric_version));
CREATE TABLE llmops.review_label (
  label_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE,
  release_id text NOT NULL REFERENCES llmops.releases(id) ON DELETE CASCADE,
  run_id text NOT NULL, node text,            -- node null = the whole Run
  label text NOT NULL, label_list_version text NOT NULL, rubric_scores text,
  by_alias text NOT NULL, reason text NOT NULL, created_at double precision NOT NULL);
CREATE TABLE llmops.auto_wheel (
  wheel_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE,
  seq integer NOT NULL,                       -- A-<seq>, from 1 per Project
  kind text NOT NULL CHECK (kind IN ('performance', 'efficiency')),
  started_by text NOT NULL,                   -- '자동(진단 신호)' · …
  base_release_id text NOT NULL REFERENCES llmops.releases(id) ON DELETE CASCADE, base_revision text NOT NULL,
  scope text NOT NULL, goal text NOT NULL,    -- 옵션만 · 정확도 (fixed for automatic wheels, D-106)
  cell integer NOT NULL CHECK (cell BETWEEN 1 AND 8),
  cell_state text NOT NULL CHECK (cell_state IN ('running', 'waiting', 'human', 'stopped', 'done')),
  iteration integer NOT NULL DEFAULT 1, settings text NOT NULL,   -- the settings in force when the wheel started
  outcome text, started_at double precision NOT NULL, ended_at double precision,
  UNIQUE (project_id, seq));
CREATE UNIQUE INDEX auto_wheel_one_open ON llmops.auto_wheel (project_id) WHERE ended_at IS NULL;   -- one wheel at a time (D-97)
CREATE TABLE llmops.auto_wheel_log (
  log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wheel_id bigint NOT NULL REFERENCES llmops.auto_wheel(wheel_id) ON DELETE CASCADE,
  cell integer NOT NULL, text text NOT NULL, created_at double precision NOT NULL);
CREATE TABLE llmops.auto_hypothesis (
  hypothesis_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wheel_id bigint NOT NULL REFERENCES llmops.auto_wheel(wheel_id) ON DELETE CASCADE,
  iteration integer NOT NULL, batch text NOT NULL CHECK (batch IN ('first', 'waiting')), batch_no integer NOT NULL,
  node text NOT NULL, knob text NOT NULL, value text,
  cheap_test text, result text, discarded_reason text, source text NOT NULL,   -- source = 'harness' in this run (agent = A6)
  created_at double precision NOT NULL);
CREATE TABLE llmops.auto_settings (
  project_id text PRIMARY KEY REFERENCES llmops.projects(id) ON DELETE CASCADE,
  data text NOT NULL, updated_by text NOT NULL, updated_at double precision NOT NULL);
CREATE TABLE llmops.fixed_flow (
  release_id text PRIMARY KEY REFERENCES llmops.releases(id) ON DELETE CASCADE,
  pack_revision text NOT NULL, items text NOT NULL, knob_ranges text NOT NULL,
  confirmed_by text, confirmed_at double precision, updated_at double precision NOT NULL);

GRANT SELECT, INSERT, UPDATE, DELETE ON llmops.ops_diagnosis, llmops.auto_wheel, llmops.auto_settings, llmops.fixed_flow TO llmops_app;
GRANT SELECT, INSERT ON llmops.review_label, llmops.auto_wheel_log, llmops.auto_hypothesis TO llmops_app;
GRANT USAGE, SELECT ON SEQUENCE llmops.ops_diagnosis_diagnosis_id_seq, llmops.review_label_label_id_seq, llmops.auto_wheel_wheel_id_seq,
  llmops.auto_wheel_log_log_id_seq, llmops.auto_hypothesis_hypothesis_id_seq TO llmops_app;
