-- EV-029 CHG-131 (10-20 PG move, answer 022-04 Q-1 A): the LLMOps store in the shared PostgreSQL `llmops` schema with the
-- SAME tables and columns as llmops/store.py SCHEMA (SQLite), so the Store's PG backend and the move tool keep every meaning.
-- JSON stays text, times stay epoch seconds (double precision). The four SQLite tables listed by rowid get an `ord` identity
-- column (last, after the SQLite columns) for the same order. Append only (Q-5 A): triggers on decision · deployment ·
-- evaluation_case · case_promotion (as in SQLite) and grants (llmops_app has no UPDATE · DELETE on those and on verdicts —
-- verdicts have no trigger, as in SQLite, because a Run or Project delete removes them by CASCADE, AC-21). The legacy candidate
-- tables are not made (S-15). Run by db_owner through dbadmin migrate; the shared databases only after the user's A5.

CREATE TABLE llmops.projects (
  id text PRIMARY KEY, name text NOT NULL, description text NOT NULL DEFAULT '',
  scoring text NOT NULL, rule text NOT NULL, created_at double precision NOT NULL);
CREATE TABLE llmops.validation_data (
  project_id text PRIMARY KEY REFERENCES llmops.projects(id) ON DELETE CASCADE,
  name text NOT NULL, cases text NOT NULL, created_at double precision NOT NULL);
CREATE TABLE llmops.releases (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE,
  name text NOT NULL, how text NOT NULL, path text NOT NULL, color text NOT NULL,
  code_hash text NOT NULL, graph text NOT NULL, env_excluded text NOT NULL DEFAULT '[]',
  last_run_code text, created_at double precision NOT NULL, updated_at double precision NOT NULL);
CREATE TABLE llmops.runs (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE, seq integer NOT NULL,
  release_id text NOT NULL REFERENCES llmops.releases(id) ON DELETE CASCADE, meta text NOT NULL, status text NOT NULL,
  created_at double precision NOT NULL, finished_at double precision);
CREATE TABLE llmops.run_cases (
  run_id text NOT NULL REFERENCES llmops.runs(id) ON DELETE CASCADE, idx integer NOT NULL, data text NOT NULL,
  PRIMARY KEY (run_id, idx));
CREATE TABLE llmops.input_sets (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE, name text NOT NULL, source text NOT NULL,
  release_name text, provider text, cases text NOT NULL, created_at double precision NOT NULL,
  ord bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE llmops.bundles (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE, input text NOT NULL, runs text NOT NULL,
  created_at double precision NOT NULL,
  ord bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE llmops.briefs (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE, title text NOT NULL, fields text NOT NULL,
  created_at double precision NOT NULL, updated_at double precision NOT NULL,
  ord bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE llmops.verdicts (
  run_id text NOT NULL REFERENCES llmops.runs(id) ON DELETE CASCADE, seq integer NOT NULL, data text NOT NULL,
  PRIMARY KEY (run_id, seq));
CREATE TABLE llmops.pack_releases (
  release_id text PRIMARY KEY REFERENCES llmops.releases(id) ON DELETE CASCADE, data text NOT NULL);
CREATE TABLE llmops.eval_suites (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE, data text NOT NULL,
  created_at double precision NOT NULL,
  ord bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE llmops.run_events (
  run_id text NOT NULL REFERENCES llmops.runs(id) ON DELETE CASCADE, seq integer NOT NULL, data text NOT NULL,
  PRIMARY KEY (run_id, seq));
CREATE TABLE llmops.decision (
  decision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_kind text NOT NULL CHECK (subject_kind IN ('candidate', 'deployment')),
  subject_id text NOT NULL,
  decision text NOT NULL CHECK (decision IN ('change_approved', 'hold', 'rejected', 'deploy_approved', 'deploy_bootstrap',
                                             'deploy_rolled_back', 'deploy_retired')),
  reason text NOT NULL CHECK (length(btrim(reason)) > 0), decided_by text NOT NULL CHECK (length(btrim(decided_by)) > 0),
  evidence text NOT NULL DEFAULT '[]', decided_at double precision NOT NULL);
CREATE TABLE llmops.deployment (
  deployment_id text NOT NULL, pack_id text NOT NULL, pack_revision text NOT NULL, data_release_id text NOT NULL,
  release_bindings text NOT NULL, runtime_version text NOT NULL, pack_commit text, pack_tag text, config_sha256 text NOT NULL,
  decision_id bigint NOT NULL REFERENCES llmops.decision(decision_id), created_at double precision NOT NULL,
  PRIMARY KEY (deployment_id, pack_revision, data_release_id));
CREATE TABLE llmops.evaluation_case (
  evaluation_run_id text NOT NULL, case_index integer NOT NULL, case_id text, run_id text NOT NULL,
  PRIMARY KEY (evaluation_run_id, case_index));
CREATE TABLE llmops.release_edit (
  edit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id text NOT NULL REFERENCES llmops.projects(id) ON DELETE CASCADE,
  release_id text NOT NULL REFERENCES llmops.releases(id) ON DELETE CASCADE, base_dir text NOT NULL, base_revision text NOT NULL,
  lines text NOT NULL DEFAULT '[]', revision text, check_result text NOT NULL DEFAULT '{}', graph text,
  started_at double precision NOT NULL, updated_at double precision NOT NULL, ended text, ended_at double precision,
  result_release_id text, memo text);
CREATE UNIQUE INDEX release_edit_one_open ON llmops.release_edit(project_id) WHERE ended IS NULL;
CREATE TABLE llmops.node_layout (owner text PRIMARY KEY, positions text NOT NULL, updated_at double precision NOT NULL);
CREATE TABLE llmops.case_promotion (
  promotion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id text NOT NULL, release_id text NOT NULL,
  source_run_id text NOT NULL, deployment_id text, source_pack_revision text NOT NULL, input_ref text NOT NULL, input text NOT NULL,
  observed text NOT NULL,
  promoted_by text NOT NULL CHECK (length(btrim(promoted_by)) > 0), reason text NOT NULL CHECK (length(btrim(reason)) > 0),
  promoted_at double precision NOT NULL, UNIQUE (project_id, source_run_id));

-- The contract's evaluation_run columns over runs (same as the SQLite view; text JSON read with ->>)
CREATE VIEW llmops.evaluation_run AS
  SELECT id AS evaluation_run_id, project_id, release_id, (meta::json) ->> 'label' AS label,
         (meta::json) -> 'input' ->> 'kind' AS input_kind, (meta::json) -> 'input' ->> 'id' AS input_id,
         (meta::json) -> 'input' ->> 'suite_revision' AS suite_revision, (meta::json) -> 'input' ->> 'dataset_hash' AS dataset_hash,
         (meta::json) ->> 'data_release_id' AS data_release_id, status, created_at
  FROM llmops.runs;

-- Append only, as the SQLite triggers (also against the owner)
CREATE FUNCTION llmops.append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append only', TG_TABLE_NAME;
END $$;
CREATE TRIGGER decision_append_only BEFORE UPDATE OR DELETE ON llmops.decision FOR EACH ROW EXECUTE FUNCTION llmops.append_only();
CREATE TRIGGER deployment_append_only BEFORE UPDATE OR DELETE ON llmops.deployment FOR EACH ROW EXECUTE FUNCTION llmops.append_only();
CREATE TRIGGER evaluation_case_append_only BEFORE UPDATE OR DELETE ON llmops.evaluation_case FOR EACH ROW EXECUTE FUNCTION llmops.append_only();
CREATE TRIGGER case_promotion_append_only BEFORE UPDATE OR DELETE ON llmops.case_promotion FOR EACH ROW EXECUTE FUNCTION llmops.append_only();

-- llmops_app (the LLMOps server and the move tool) — change contract v5 permission table
GRANT USAGE ON SCHEMA llmops TO llmops_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON llmops.projects, llmops.validation_data, llmops.releases, llmops.runs, llmops.run_cases,
  llmops.input_sets, llmops.bundles, llmops.briefs, llmops.pack_releases, llmops.eval_suites, llmops.run_events,
  llmops.release_edit, llmops.node_layout TO llmops_app;
GRANT SELECT, INSERT ON llmops.verdicts, llmops.decision, llmops.deployment, llmops.evaluation_case, llmops.case_promotion TO llmops_app;
GRANT SELECT ON llmops.evaluation_run, llmops.schema_version TO llmops_app;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE llmops.decision_decision_id_seq, llmops.release_edit_edit_id_seq,
  llmops.case_promotion_promotion_id_seq, llmops.eval_suites_ord_seq, llmops.input_sets_ord_seq, llmops.bundles_ord_seq,
  llmops.briefs_ord_seq TO llmops_app;
